/*  Realistic 3D Human Explorer Scale Reference (reused from Human Atlas 3D)  */
/* -------------------------------------------------------------------------- */

export const HumanScaleExplorer: React.FC<{
  animal: AnimalRecord;
  modelLength: number;
}> = ({ animal, modelLength }) => {
  const skinGltf = useGLTF('/models/human-skin.glb', false, false);
  const organsGltf = useGLTF('/models/human-organs.glb', false, false);
  const rootRef = useRef<THREE.Group>(null);

  const raw =
    (KID_HEIGHT_M / Math.max(animal.metrics.lengthMeters, 0.01)) *
    (modelLength / 1.6);
  const ratio = Math.min(Math.max(raw, 0.16), 2.2);
  const clamped = Math.abs(ratio - raw) > 0.01;
  const unitScale = (1.6 / NATIVE_HUMAN_HEIGHT) * ratio;

  const { holder, materials, garmentGeo, garmentMat } = useMemo(() => {
    const mats = new TissueMaterialLibrary();
    const h = new THREE.Group();
    const groups: Record<string, THREE.Group> = {
      skin: new THREE.Group(),
      organs: new THREE.Group(),
      heart: new THREE.Group(),
      eyes: new THREE.Group(),
    };
    h.add(groups.skin, groups.eyes);

    const { skinMesh } = ingestHumanLayer('skin', skinGltf.scene, mats, groups);
    ingestHumanLayer('organs', organsGltf.scene, mats, groups);

    let gGeo: THREE.BufferGeometry | null = null;
    let gMat: THREE.Material | null = null;
    if (skinMesh) {
      computeFaceLandmarks(skinMesh, mats);
      const garment = buildModestyGarment(skinMesh, mats, 0x1f3a60);
      if (garment) {
        groups.skin.add(garment);
        gGeo = garment.geometry;
        gMat = garment.material as THREE.Material;
      }
    }
    mats.setLayerOpacity('skin', 1.0);
    mats.setLayerOpacity('eyes', 1.0);
    return { holder: h, materials: mats, garmentGeo: gGeo, garmentMat: gMat };
  }, [skinGltf.scene, organsGltf.scene]);

  useEffect(() => {
    return () => {
      materials.allMaterials().forEach((m) => m.dispose());
      garmentGeo?.dispose();
      garmentMat?.dispose();
    };
  }, [materials, garmentGeo, garmentMat]);

  useFrame(() => {
    if (rootRef.current) {
      rootRef.current.updateMatrixWorld();
      materials.shared.uHumanRootInv.value.copy(rootRef.current.matrixWorld).invert();
    }
  });

  const isAquatic = [
    'cetacean',
    'shark_ichthyosaur',
    'cephalopod',
    'marine_reptile',
  ].includes(animal.archetype);
  const baseY = isAquatic ? -0.45 : -1.0;
  const posX = isAquatic ? 0.25 : -0.78;
  const posZ = 0.62;

  return (
    <group position={[posX, baseY, posZ]} rotation={[0, Math.PI * 0.16, 0]}>
      <group ref={rootRef} scale={[unitScale, unitScale, unitScale]}>
        <primitive object={holder} />
      </group>
      <SafeHtml3D position={[0, 1.68 * ratio + 0.08, 0]} center zIndexRange={[15, 0]}>
        <div className="px-2 py-0.5 rounded-full bg-sky-950/90 border border-sky-400/50 text-[10px] font-semibold text-sky-100 whitespace-nowrap shadow-lg">
          🧑 Human Explorer (1.45 m) vs {animal.metrics.lengthMeters} m {animal.commonName}
          {clamped && <span className="text-sky-300/80"> · rescaled for view</span>}
        </div>
      </SafeHtml3D>
    </group>
  );
};

