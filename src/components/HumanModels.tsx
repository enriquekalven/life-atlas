const LIP_CENTER: [number, number, number] = [0, 1.535, 0.0827];
const EYE_LEFT_CENTER: [number, number, number] = [0.0298, 1.5962, 0.0504];
const EYE_RIGHT_CENTER: [number, number, number] = [-0.0298, 1.5962, 0.0504];
