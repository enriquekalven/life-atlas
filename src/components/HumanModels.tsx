/**
 * Principal axis of the vertex cloud approximates the muscle-fibre / fascicle direction
 * (ported directly from human-body-3d-atlas/src/viewer/AnatomyViewer.js).
 */
function addFiberAttribute(mesh: THREE.Mesh) {
  const pos = mesh.geometry?.attributes?.position;
  if (!pos || mesh.geometry.attributes.fiberDir) return;
  const n = pos.count;
  if (n < 3) return;
  let mx = 0;
  let my = 0;
  let mz = 0;
  for (let i = 0; i < n; i++) {
    mx += pos.getX(i);
    my += pos.getY(i);
    mz += pos.getZ(i);
  }
  mx /= n;
  my /= n;
  mz /= n;
  let xx = 0,
    xy = 0,
    xz = 0,
    yy = 0,
    yz = 0,
    zz = 0;
  for (let i = 0; i < n; i++) {
    const x = pos.getX(i) - mx;
    const y = pos.getY(i) - my;
    const z = pos.getZ(i) - mz;
    xx += x * x;
    xy += x * y;
    xz += x * z;
    yy += y * y;
    yz += y * z;
    zz += z * z;
  }
  let v = [0.3, 1, 0.2];
  for (let it = 0; it < 20; it++) {
    const nx = xx * v[0] + xy * v[1] + xz * v[2];
    const ny = xy * v[0] + yy * v[1] + yz * v[2];
    const nz = xz * v[0] + yz * v[1] + zz * v[2];
    const l = Math.hypot(nx, ny, nz) || 1;
    v = [nx / l, ny / l, nz / l];
  }
  const arr = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) {
    arr[i * 3] = v[0];
    arr[i * 3 + 1] = v[1];
    arr[i * 3 + 2] = v[2];
  }
  mesh.geometry.setAttribute('fiberDir', new THREE.BufferAttribute(arr, 3));
}

/**
 * Locates nose tip, cheeks, ears and lip center on the real skin surface for vascular flush
 * and smooth vermilion lip shading (ported from human-body-3d-atlas/src/viewer/AnatomyViewer.js).
 */
function computeFaceLandmarks(skin: THREE.Mesh, materials: TissueMaterialLibrary) {
  materials.shared.uLipPos.value.set(LIP_CENTER[0], LIP_CENTER[1], LIP_CENTER[2], 1.0);
  const eyeY = (EYE_LEFT_CENTER[1] + EYE_RIGHT_CENTER[1]) / 2;
  const eyeZ = (EYE_LEFT_CENTER[2] + EYE_RIGHT_CENTER[2]) / 2;
  const eyeX = Math.abs(EYE_LEFT_CENTER[0] - EYE_RIGHT_CENTER[0]) / 2;
  const pos = skin.geometry.attributes.position;
  if (!pos) return;
  const v = new THREE.Vector3();
  let nose: THREE.Vector3 | null = null;
  let cheekL: THREE.Vector3 | null = null;
  let cheekR: THREE.Vector3 | null = null;
  let earL: THREE.Vector3 | null = null;
  let earR: THREE.Vector3 | null = null;
  skin.updateMatrixWorld(true);
  for (let i = 0; i < pos.count; i++) {
    v.fromBufferAttribute(pos, i).applyMatrix4(skin.matrixWorld);
    if (v.y > eyeY + 0.06 || v.y < LIP_CENTER[1] - 0.03) continue;
    if (
      Math.abs(v.x) < 0.012 &&
      v.y < eyeY - 0.01 &&
      v.y > LIP_CENTER[1] + 0.012 &&
      (!nose || v.z > nose.z)
    ) {
      nose = v.clone();
    }
    if (Math.abs(v.y - (eyeY - 0.032)) < 0.006) {
      if (Math.abs(v.x - eyeX * 1.15) < 0.006 && (!cheekL || v.z > cheekL.z)) cheekL = v.clone();
      if (Math.abs(v.x + eyeX * 1.15) < 0.006 && (!cheekR || v.z > cheekR.z)) cheekR = v.clone();
    }
    if (Math.abs(v.y - (eyeY - 0.012)) < 0.02 && v.z < eyeZ - 0.05 && v.z > eyeZ - 0.14) {
      if (v.x > 0 && (!earL || v.x > earL.x)) earL = v.clone();
      if (v.x < 0 && (!earR || v.x < earR.x)) earR = v.clone();
    }
  }
  const spots: Array<[THREE.Vector3 | null, number]> = [
    [nose, 0.013],
    [cheekL, 0.024],
    [cheekR, 0.024],
    [earL, 0.02],
    [earR, 0.02],
  ];
  const uniform = materials.shared.uFlushPts.value;
  spots.forEach(([p, radius], k) => {
    if (p) uniform[k].set(p.x, p.y, p.z, radius);
  });
  materials.shared.uFlush.value = 0.6;
}

/**
 * Kids-mode modesty athletic boxer shorts generated by slicing 2D convex hulls directly from
 * the real FJ2810 skin surface (ported verbatim from human-body-3d-atlas/src/viewer/AnatomyViewer.js).
 */
function buildModestyGarment(
  skin: THREE.Mesh,
  materials: TissueMaterialLibrary,
  garmentColorHex = 0x1f3a60
): THREE.Mesh | null {
  skin.updateMatrixWorld(true);
  const pos = skin.geometry.attributes.position;
  if (!pos) return null;
  const H = NATIVE_HUMAN_HEIGHT;
  const yTop = H * 0.572; // waistband, just below the iliac crests
  const yLeg = H * 0.405; // hem, upper-mid thigh
  const v = new THREE.Vector3();
  const band: Array<[number, number, number]> = [];
  let yGen = Infinity;
  for (let i = 0; i < pos.count; i++) {
    v.fromBufferAttribute(pos, i).applyMatrix4(skin.matrixWorld);
    if (v.y >= yLeg - 0.025 && v.y <= yTop + 0.025 && Math.abs(v.x) <= 0.32) {
      band.push([v.x, v.y, v.z]);
      if (Math.abs(v.x) < 0.02 && v.y < H * 0.5 && v.y < yGen) yGen = v.y;
    }
  }
  if (band.length < 400) return null;
  const yJoin = Number.isFinite(yGen) ? Math.max(yLeg + 0.04, yGen - 0.012) : H * 0.455;
  const M = 72;

  const dropHands = (pts: Array<[number, number, number]>, maxAbsX = 0.175) => {
    const xs = pts.map((p) => p[0]).sort((a, b) => a - b);
    const clusters: Array<[number, number]> = [];
    let start = xs[0];
    for (let k = 1; k <= xs.length; k++) {
      if (k === xs.length || xs[k] - xs[k - 1] > 0.018) {
        clusters.push([start, xs[k - 1]]);
        start = xs[k];
      }
    }
    const keep = clusters.filter(
      ([a, b]) => (a <= 0 && b >= 0 ? 0 : Math.min(Math.abs(a), Math.abs(b))) < maxAbsX
    );
    return pts.filter((p) => keep.some(([a, b]) => p[0] >= a && p[0] <= b));
  };

  const hull2 = (pts: Array<[number, number, number]>) => {
    const P = pts.map((p) => [p[0], p[2]] as [number, number]).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
    const cross = (o: [number, number], a: [number, number], b: [number, number]) =>
      (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
    const lower: Array<[number, number]> = [];
    const upper: Array<[number, number]> = [];
    for (const p of P) {
      while (lower.length >= 2 && cross(lower[lower.length - 2], lower[lower.length - 1], p) <= 0) {
        lower.pop();
      }
      lower.push(p);
    }
    for (let i = P.length - 1; i >= 0; i--) {
      const p = P[i];
      while (upper.length >= 2 && cross(upper[upper.length - 2], upper[upper.length - 1], p) <= 0) {
        upper.pop();
      }
      upper.push(p);
    }
    upper.pop();
    lower.pop();
    return lower.concat(upper);
  };

  const radial = (hull: Array<[number, number]>, c: [number, number]) => {
    const r = new Float32Array(M);
    for (let j = 0; j < M; j++) {
      const th = (j / M) * Math.PI * 2;
      const dx = Math.cos(th);
      const dz = Math.sin(th);
      let best = 0;
      for (let k = 0; k < hull.length; k++) {
        const p = hull[k];
        const q = hull[(k + 1) % hull.length];
        const ex = q[0] - p[0];
        const ez = q[1] - p[1];
        const den = dx * ez - dz * ex;
        if (Math.abs(den) < 1e-12) continue;
        const wx = p[0] - c[0];
        const wz = p[1] - c[1];
        const t = (wx * ez - wz * ex) / den;
        const u = (wx * dz - wz * dx) / den;
        if (t > 0 && u >= -1e-6 && u <= 1 + 1e-6) best = Math.max(best, t);
      }
      r[j] = best;
    }
    return r;
  };

  interface GarmentRing {
    y: number;
    c: [number, number];
    r: Float32Array;
  }

  const sliceRings = (
    srcPts: Array<[number, number, number]>,
    y0: number,
    y1: number,
    filter: (p: [number, number, number]) => boolean,
    maxAbsX = 0.175
  ): GarmentRing[] => {
    const rings: GarmentRing[] = [];
    const dy = 0.008;
    const win = dy * 1.75;
    for (let y = y0; y >= y1 - 1e-6; y -= dy) {
      let pts = srcPts.filter((p) => Math.abs(p[1] - y) <= win && filter(p));
      if (pts.length < 12) continue;
      pts = dropHands(pts, maxAbsX);
      if (pts.length < 12) continue;
      const hull = hull2(pts);
      if (hull.length < 3) continue;
      const c = hull.reduce<[number, number]>(
        (s, p) => [s[0] + p[0] / hull.length, s[1] + p[1] / hull.length],
        [0, 0]
      );
      rings.push({ y, c, r: radial(hull, c) });
    }
    return rings;
  };

  const smoothRings = (rings: GarmentRing[], offset: number) => {
    for (const ring of rings) {
      const r = ring.r.slice();
      for (let j = 0; j < M; j++) {
        ring.r[j] = Math.max(r[(j + M - 1) % M], r[j], r[(j + 1) % M]);
      }
    }
    const dilV = rings.map((g) => g.r.slice());
    for (let s = 0; s < rings.length; s++) {
      const s0 = Math.max(0, s - 1);
      const s1 = Math.min(rings.length - 1, s + 1);
      for (let j = 0; j < M; j++) {
        rings[s].r[j] = Math.max(dilV[s0][j], dilV[s][j], dilV[s1][j]);
      }
    }
    for (let pass = 0; pass < 4; pass++) {
      for (const ring of rings) {
        const r = ring.r.slice();
        for (let j = 0; j < M; j++) {
          ring.r[j] = (r[(j + M - 1) % M] + 2 * r[j] + r[(j + 1) % M]) / 4;
        }
      }
    }
    for (let pass = 0; pass < 4; pass++) {
      const rs = rings.map((g) => g.r.slice());
      const cs = rings.map((g) => g.c.slice() as [number, number]);
      for (let s = 1; s < rings.length - 1; s++) {
        for (let j = 0; j < M; j++) {
          rings[s].r[j] = (rs[s - 1][j] + 2 * rs[s][j] + rs[s + 1][j]) / 4;
        }
        rings[s].c = [
          (cs[s - 1][0] + 2 * cs[s][0] + cs[s + 1][0]) / 4,
          (cs[s - 1][1] + 2 * cs[s][1] + cs[s + 1][1]) / 4,
        ];
      }
    }
    for (const ring of rings) {
      for (let j = 0; j < M; j++) ring.r[j] += offset;
    }
  };

  const positions: number[] = [];
  const indices: number[] = [];
  const addTube = (rings: GarmentRing[], capBottom: boolean) => {
    if (rings.length < 2) return;
    const base = positions.length / 3;
    for (const ring of rings) {
      for (let j = 0; j < M; j++) {
        const th = (j / M) * Math.PI * 2;
        positions.push(
          ring.c[0] + ring.r[j] * Math.cos(th),
          ring.y,
          ring.c[1] + ring.r[j] * Math.sin(th)
        );
      }
    }
    for (let s = 0; s < rings.length - 1; s++) {
      for (let j = 0; j < M; j++) {
        const a = base + s * M + j;
        const b = base + s * M + ((j + 1) % M);
        const c = base + (s + 1) * M + ((j + 1) % M);
        const d = base + (s + 1) * M + j;
        indices.push(a, b, d, b, c, d);
      }
    }
    if (capBottom) {
      const last = rings[rings.length - 1];
      const capBase = positions.length / 3;
      for (let j = 0; j < M; j++) {
        const th = (j / M) * Math.PI * 2;
        positions.push(
          last.c[0] + last.r[j] * Math.cos(th),
          last.y,
          last.c[1] + last.r[j] * Math.sin(th)
        );
      }
      const centre = positions.length / 3;
      positions.push(last.c[0], last.y, last.c[1]);
      for (let j = 0; j < M; j++) indices.push(capBase + j, capBase + ((j + 1) % M), centre);
    }
  };

  const pelvis = sliceRings(band, yTop, yJoin, () => true);
  smoothRings(pelvis, 0.0085);
  addTube(pelvis, true);
  for (const side of [-1, 1]) {
    const leg = sliceRings(band, yJoin + 0.036, yLeg, (p) => p[0] * side > 0.004);
    smoothRings(leg, 0.008);
    addTube(leg, false);
  }
  if (indices.length < 300) return null;
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3));
  g.setIndex(indices);
  g.computeVertexNormals();
  const mat = new THREE.MeshPhysicalMaterial({
    color: garmentColorHex,
    roughness: 0.86,
    sheen: 1.0,
    sheenColor: new THREE.Color(0x5b7fb8),
    sheenRoughness: 0.5,
    side: THREE.DoubleSide,
  });
  materials.applyDanceToMaterial(mat);
  const mesh = new THREE.Mesh(g, mat);
  mesh.name = 'modesty-garment-male';
  mesh.castShadow = true;
  mesh.receiveShadow = true;
  return mesh;
}

/**
 * Ingests a GLTF layer scene using the exact TissueMaterialLibrary and male filtering
 * from human-body-3d-atlas/src/viewer/AnatomyViewer.js.
 */
function ingestHumanLayer(
  layerId: string,
  rawScene: THREE.Group,
  materials: TissueMaterialLibrary,
  groups: Record<string, THREE.Group>,
  pivots?: {
    heart: THREE.Group;
    lungs: THREE.Group;
    diaphragm: THREE.Group;
  }
): { skinMesh: THREE.Mesh | null } {
  const cloned = rawScene.clone(true);
  cloned.updateMatrixWorld(true);
  const meshes: THREE.Mesh[] = [];
  cloned.traverse((o) => {
    if ((o as THREE.Mesh).isMesh) meshes.push(o as THREE.Mesh);
  });

  let skinMesh: THREE.Mesh | null = null;
  for (const mesh of meshes) {
    const ud = mesh.userData || {};
    const fj = String(ud.fj || '');
    const partSex = ud.sex || (fj.endsWith('F') ? 'female' : fj === 'FJ3148' ? 'male' : '');
    if (partSex && partSex !== 'male') {
      mesh.visible = false;
      continue;
    }
    const meshName = String(mesh.name || mesh.parent?.name || '');
    if (
      ud.group === 'reproductive' ||
      ud.mat === 'reproductive' ||
      (layerId === 'organs' && Boolean(ud.sex)) ||
      fj === 'FJ3148' ||
      /penis|testis|scrot|epididym|deferen|prostate|seminal|bulbospong|ischiocav|cremaster|urethra|vagina|uter|ovary|fallopian|cervix|mammary|lactifer/i.test(
        meshName
      )
    ) {
      mesh.visible = false;
      continue;
    }

    const tissue = ud.mat || 'organ';
    let layerKey = layerId;
    if ((ud.group === 'heart' || tissue === 'heart') && layerId === 'organs') {
      layerKey = 'heart';
    }
    if (tissue === 'eye' || tissue === 'iris' || tissue === 'cornea' || tissue === 'pupil') {
      layerKey = 'eyes';
    }
    const entry = materials.get(layerKey, tissue);
    mesh.material = entry.base;
    mesh.userData.entry = entry;
    mesh.userData.layerKey = layerKey;
    mesh.castShadow = layerId !== 'vessels' && layerId !== 'nerves' && tissue !== 'lip';
    mesh.receiveShadow = tissue !== 'lip';

    if (entry.def.pickProxy) {
      mesh.visible = false;
    }
    if (entry.def.fiber) {
      addFiberAttribute(mesh);
    }
    if (fj === 'FJ2810') {
      skinMesh = mesh;
    }

    let parent = groups[layerKey] || groups[layerId];
    if (pivots) {
      if (layerKey === 'heart') parent = pivots.heart;
      else if (layerId === 'organs' && tissue === 'lung') parent = pivots.lungs;
      else if (layerId === 'muscles' && /^diaphragm/i.test(mesh.name || '')) parent = pivots.diaphragm;
    }
    if (parent) {
      parent.attach(mesh);
    }
  }
  return { skinMesh };
}

